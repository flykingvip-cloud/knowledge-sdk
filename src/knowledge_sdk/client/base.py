from __future__ import annotations
from typing import Protocol
class KnowledgeClient(Protocol):
    def create_kb(self, actor, name, visibility="private", kb_id=None, *, space_type=None, owner_department_id="", owner_user_id=""): ...
    def list_kbs(self, actor): ...
    def grant_kb_member(self, actor, kb_id, user_id, role): ...
    def ingest(self, actor, kb_id, content, filename="document.txt", title=None, visibility=None, doc_id=None, metadata=None): ...
    def list_documents(self, actor, kb_id=None, include_archived=False): ...
    def get_document(self, actor, doc_id, version=None): ...
    def preview(self, actor, doc_id, version=None, limit=800): ...
    def archive(self, actor, doc_id): ...
    def restore(self, actor, doc_id): ...
    def set_document_acl(self, actor, doc_id, acl): ...
    def search(self, actor, query, mode="keyword", limit=20, filters=None): ...
    def retrieve(self, actor, doc_id, version=None, chunk_ids=None, offset=0, limit=8000): ...
    def reference(self, actor, doc_id, version=None, chunk_ids=None, excerpt=""): ...
    def consume(self, actor, ref): ...
    def batch_consume(self, actor, refs): ...
    def reindex(self, actor, kb_id): ...
    def health(self): ...
    def ask(self, actor, question: str, scope=None, top_k: int = 5, mode: str = "keyword", generator=None, excerpt_policy=None, min_score: float = 0.0, binding=None): ...
    def create_ref(self, actor, doc_id: str, version=None, chunk_ids=None, excerpt: str = ""): ...
    def attach(self, actor, ref, binding=None): ...
    def verify_ref(self, actor, ref): ...
    def verify_receipt(self, actor, ref, receipt, binding=None): ...
    def validate_scope(self, actor, scope): ...
    def validate_binding(self, actor, binding): ...
    def bind_consumer(self, actor, binding): ...
    def get_consumer_binding(self, actor, consumer_type: str, consumer_id: str): ...
    def can_manage_kb(self, actor, kb_id: str) -> bool: ...
    def can_upload_to_kb(self, actor, kb_id: str) -> bool: ...
