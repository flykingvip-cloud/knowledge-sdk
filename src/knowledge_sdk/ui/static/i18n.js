export const LANGUAGE_KEY = 'knowledge-workbench-language';
export function normalizeLanguage(value) { return value === 'en' ? 'en' : 'zh-CN'; }
let language = 'zh-CN';
try { language = normalizeLanguage(window.localStorage.getItem(LANGUAGE_KEY)); } catch { /* Storage may be blocked. */ }
export function getLanguage() { return language; }
export function t(key, ...values) {
  const entry = messages[key];
  const template = entry?.[language] || entry?.['zh-CN'] || messages['操作失败，请检查权限、输入或服务连接。'][language];
  return template.replace(/\{(\d+)\}/g, (_, i) => String(values[Number(i)] ?? ''));
}
export function setLanguage(value) {
  language = normalizeLanguage(value);
  try { window.localStorage.setItem(LANGUAGE_KEY, language); } catch { /* Preference still applies for this session. */ }
  return language;
}
export function localize(root = document) {
  if (root.documentElement) root.documentElement.lang = language;
  root.querySelectorAll('[data-i18n]').forEach(node => { node.textContent = t(node.getAttribute('data-i18n')); });
  for (const attr of ['placeholder', 'aria-label']) {
    root.querySelectorAll(`[data-i18n-${attr}]`).forEach(node => { node.setAttribute(attr, t(node.getAttribute(`data-i18n-${attr}`))); });
  }
}
export function errorText() { return t('操作失败，请检查权限、输入或服务连接。'); }
