from __future__ import annotations
from typing import Protocol, Optional, List, ContextManager
from ..contracts.models import Document, DocumentVersion, KnowledgeBase, DocumentACL, Chunk
class MetadataStore(Protocol):
    def transaction(self) -> ContextManager: ...
    def get_kb(self, kb_id: str) -> KnowledgeBase: ...
    def list_kbs(self, org_id: str) -> List[KnowledgeBase]: ...
    def put_kb(self, kb: KnowledgeBase) -> None: ...
    def grant_member(self, kb_id: str, user_id: str, role: str) -> None: ...
    def member_role(self, kb_id: str, user_id: str) -> Optional[str]: ...
    def get_document(self, doc_id: str) -> Document: ...
    def put_document(self, document: Document) -> None: ...
    def list_documents(self, org_id: str) -> List[Document]: ...
    def get_version(self, doc_id: str, version: int) -> DocumentVersion: ...
    def put_version(self, version: DocumentVersion, chunks: List[Chunk]) -> None: ...
    def get_chunks(self, doc_id: str, version: int) -> List[Chunk]: ...
    def get_acl(self, doc_id: str) -> DocumentACL: ...
    def set_acl(self, doc_id: str, acl: DocumentACL) -> None: ...
    def refresh_fts(self, doc_id: str) -> None: ...
    def keyword_search(self, query: str, org_id: str, limit: int = 100) -> list: ...
    def mark_pending(self, doc_id: str, pending: bool = True) -> None: ...
    def pending_documents(self) -> List[str]: ...
    def keyword_search_pushdown(self, query: str, org_id: str, limit: int = 100, *, kb_ids=None, doc_ids=None, space_types=None) -> list: ...
    def put_issue(self, issue) -> None: ...
    def put_anchors(self, anchors) -> None: ...
    def get_anchors(self, org_id, doc_id, version) -> list: ...
    def get_anchor(self, org_id, doc_id, version, anchor_id): ...
    def update_anchor(self, anchor) -> None: ...
    def put_policy_rule(self, rule) -> None: ...
    def list_policy_rules(self, org_id) -> list: ...
    def delete_policy_rule(self, org_id, rule_id) -> None: ...
    def append_audit_event(self, event): ...
    def list_audit_events(self, org_id, *, doc_id=None, actor_id=None, action=None, since=None, until=None, limit=100): ...
    def iter_audit_chain(self, org_id, from_seq=1, to_seq=None): ...
    def outbox_processing_scope(self, event) -> ContextManager: ...
    def enqueue_outbox(self, event): ...
    def claim_outbox_batch(self, now_iso, limit=50, *, org_id=None): ...
    def mark_outbox_dispatched(self, event_id, dispatched_at): ...
    def mark_outbox_failed(self, event_id, next_available_at, max_attempts=5): ...
    def put_webhook_subscription(self, sub): ...
    def list_webhook_subscriptions(self, org_id, *, active_only=True): ...
    def record_webhook_delivery(self, delivery): ...
    def has_webhook_delivery(self, subscription_id, outbox_event_id): ...
    def put_usage_event(self, event, *, actor=None, agent=None): ...
    def list_usage_events_for_doc(self, org_id, doc_id, *, version=None): ...
    def usage_identity(self, org_id, usage_id): ...
    def put_impact_alert(self, alert, *, actor_id='', usage_id=''): ...
    def list_impact_alerts(self, org_id, *, doc_id=None, status=None, target_id=None): ...
    def update_impact_alert_status(self, org_id, alert_id, status): ...
    def put_binding(self, actor, binding, *, agent=None, purpose='read'): ...
    def get_binding(self, actor, consumer_type, consumer_id): ...
    def list_bindings(self, actor): ...
    def list_all_bindings(self, org_id): ...
    def binding_identity(self, org_id, user_id, consumer_type, consumer_id): ...
    def impact_owner(self, org_id, alert_id): ...
    def latest_version(self,doc_id): ...
    def lock_document(self,doc_id): ...
    def put_review_decision(self,decision): ...
    def list_review_decisions(self,org_id,doc_id,version=None): ...
    def update_document_lifecycle(self,doc_id,lifecycle_state,*,current_version=None): ...
    def update_version_state(self,doc_id,version,lifecycle_state,**metadata): ...
    def update_issue(self,issue,*,expected_version=None): ...
    def put_evidence_pack(self,pack): ...
    def get_evidence_pack(self,org_id,pack_id): ...
    def list_evidence_packs(self,org_id): ...
    def mark_evidence_pack_impacted(self,org_id,pack_id): ...

class BlobStore(Protocol):
    def put(self, org_id: str, doc_id: str, raw_hash: str, data: bytes) -> str: ...
    def get(self, key: str) -> bytes: ...
